// Type-check the examples that have a tsconfig.json. Each one extends
// `./.celesta/tsconfig.json`, so first copy in the support directory the
// editor's `--init` installs, staged by `pnpm run build:runtime` at
// packages/cli/dist/project-types. Unlike `--init`, this writes nothing but
// `.celesta/`, which ignores itself in Git.
//
// An example whose celesta.config.json declares first-party plugins
// (`plugins.dependencies`, such as `code`) gets their declarations in
// `.celesta/plugins/<id>/`, as Celesta copies an installed plugin's: this
// script builds those plugins from plugins/<id> with scripts/plugins/build.mts
// first, so the check needs no registry download.
//
//   node scripts/typecheck-examples.mjs [name...]
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const examples = join(root, 'examples');
const template = join(root, 'packages', 'cli', 'dist', 'project-types');
if (!existsSync(join(template, 'version.json'))) {
  console.error(`Missing ${template}. Run \`pnpm run build:runtime\` first.`);
  process.exit(1);
}
const tsc = join(
  dirname(createRequire(join(root, 'packages', 'cli', 'package.json')).resolve('typescript/package.json')),
  'bin',
  'tsc',
);

const names = process.argv.slice(2);
const targets = names.length
  ? names
  : readdirSync(examples)
      .filter((name) => existsSync(join(examples, name, 'tsconfig.json')))
      .sort();

/** The registry plugins `project`'s celesta.config.json declares, by id. */
function declaredPlugins(project) {
  const config = join(project, 'celesta.config.json');
  if (!existsSync(config)) return [];
  return Object.keys(JSON.parse(readFileSync(config, 'utf8')).plugins?.dependencies ?? {});
}

// Every first-party plugin the examples declare, built once.
const plugins = [...new Set(targets.flatMap((name) => declaredPlugins(join(examples, name))))].sort();
for (const id of plugins) {
  if (!existsSync(join(root, 'plugins', id, 'plugin.json'))) {
    console.error(`An example declares the plugin ${id}, which is not a first-party plugin under plugins/`);
    process.exit(1);
  }
}
const built = plugins.length ? mkdtempSync(join(tmpdir(), 'celesta-example-plugins-')) : undefined;
if (built) {
  const { status } = spawnSync(
    process.execPath,
    [join(root, 'scripts', 'plugins', 'build.mts'), ...plugins.map((id) => join(root, 'plugins', id)), '--out', built],
    { stdio: 'inherit' },
  );
  if (status !== 0) {
    console.error(`Building the plugins ${plugins.join(', ')} failed.`);
    process.exit(1);
  }
  process.on('exit', () => rmSync(built, { recursive: true, force: true }));
}

let failed = 0;
for (const name of targets) {
  const project = join(examples, name);
  if (!existsSync(join(project, 'tsconfig.json'))) {
    console.error(`examples/${name} has no tsconfig.json`);
    failed++;
    continue;
  }
  // The same layout crates/react-bridge/src/project_types.rs installs.
  const support = join(project, '.celesta');
  rmSync(support, { recursive: true, force: true });
  cpSync(template, support, { recursive: true });
  writeFileSync(join(support, '.gitignore'), '# Generated by Celesta and refreshed when Celesta updates.\n*\n');
  // The declarations alone, as crates/react-bridge/src/project_types.rs copies them.
  for (const id of declaredPlugins(project)) {
    cpSync(join(built, id, 'js'), join(support, 'plugins', id), {
      recursive: true,
      filter: (source) => !source.endsWith('.js'),
    });
  }

  console.log(`examples/${name}`);
  const { status } = spawnSync(process.execPath, [tsc, '--noEmit', '-p', project], { stdio: 'inherit' });
  if (status !== 0) failed++;
}
if (failed) {
  console.error(`${failed} of ${targets.length} examples failed the type check.`);
  process.exit(1);
}
